// Endpoint construction, including that the two spec spellings of the Apple
// MDM id address the same object.
func TestDeviceEndpoints(t *testing.T) {
	const mdm, dev = "690b6c939c0bf5000100039a", "69c45aabb695320001aff063"
	for want, got := range map[string]string{
		"/applemdms/" + mdm + "/devices/" + dev:                              DeviceEndpoint(mdm, dev),
		"/applemdms/" + mdm + "/csr":                                         CSREndpoint(mdm),
		"/applemdms/" + mdm + "/devices/" + dev + "/getrecoverylockconfig":   RecoveryLockConfigEndpoint(mdm, dev),
		"/applemdms/" + mdm + "/devices/" + dev + "/getrecoverylockpassword": RecoveryLockPasswordEndpoint(mdm, dev),
		"/applemdms/" + mdm + "/devices/" + dev + "/lockstate":               LockStateEndpoint(mdm, dev),
		"/applemdms/" + mdm + "/devices/" + dev + "/lockpin":                 LockPINEndpoint(mdm, dev),
	} {
		if got != want {
			t.Errorf("endpoint = %q, want %q", got, want)
		}
	}
}
