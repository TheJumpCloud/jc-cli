// The live lockstate body, identical on all seven devices.
const lockStateLive = `{
  "failureReason": "lock_failure_reason_unspecified",
  "lockMessage": "",
  "messageResult": "message_result_unspecified",
  "phoneNumber": "",
  "state": "device_lock_console_state_unlocked",
  "statusUpdatedAt": null
}`

func TestParseLockState_SentinelsAreNotStates(t *testing.T) {
	s, err := ParseLockState(json.RawMessage(lockStateLive))
	if err != nil {
		t.Fatalf("ParseLockState: %v", err)
	}
	if s.Locked() {
		t.Error("Locked() on device_lock_console_state_unlocked returned true")
	}
	got := s.Describe()
	if !strings.Contains(got, "unlocked") {
		t.Errorf("Describe() = %q, want it to say unlocked", got)
	}
	// The sentinels mean "nothing to report" and must not be surfaced as a
	// failure the operator should act on.
	if strings.Contains(got, "unspecified") {
		t.Errorf("Describe() = %q — it leaked a protobuf sentinel", got)
	}
	if !IsUnspecified(s.FailureReason) {
		t.Errorf("IsUnspecified(%q) = false", s.FailureReason)
	}
}

// Locked() is matched against the known locked state, not against "anything
// that is not unlocked" -- otherwise a device that has never reported, or a
// sentinel added later, reads as locked.
func TestLockState_UnknownIsNotLocked(t *testing.T) {
	for name, state := range map[string]string{
		"never reported":      "",
		"the sentinel":        "device_lock_console_state_unspecified",
		"a state added later": "device_lock_console_state_pending_user_acknowledgement",
	} {
		s := LockState{State: state}
		if s.Locked() {
			t.Errorf("%s (%q): Locked() = true; only the locked state may report locked",
				name, state)
		}
	}
	if locked := (LockState{State: "device_lock_console_state_locked"}); !locked.Locked() {
		t.Error("the actual locked state did not report Locked()")
	}
}

