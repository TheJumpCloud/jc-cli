#!/usr/bin/env python3
"""Regenerate docs/spec-provenance.md — which upstream documents the
spec-derived artifacts in this repo were built from.

Usage:
    python3 scripts/spec-provenance.py URL=path [URL=path ...] [--out=PATH]

WHY THIS IS NOT A TIMESTAMP. The obvious way to record a generated file's
vintage is to stamp the date into it. That breaks the one check that makes
these artifacts trustworthy: `make verify-generated` regenerates them and
fails on any difference, so a date would make every regeneration a difference
and the check could no longer tell "the spec moved" from "somebody reran the
script".

The date was never the missing information anyway. Git already holds it, with
better provenance than a self-reported string:

    git log -1 --format=%ad -- docs/API_COVERAGE.md

What git cannot tell you is which upstream document produced the file. That is
what this records: the URL fetched and the SHA-256 of the bytes that came
back. Deterministic, so the drift check still works, and it answers the
question a reader actually has — "is this built from the spec that is up there
now?"

A DIGEST CHANGE IS NOT NECESSARILY A SEMANTIC CHANGE. It covers the whole
document, so upstream reformatting, reordering or an edited description moves
it while nothing jc derives from the spec changes at all. That is a feature of
the split: this file answers "is it the same document?", and the regenerated
artifacts answer "did anything we depend on change?". A drift PR whose only
diff is a digest means upstream republished and jc is unaffected — cheap news,
not a defect.
"""
import collections
import hashlib
import sys

try:
    import yaml
except ImportError:
    sys.exit("PyYAML required: pip install pyyaml")

OUT = "docs/spec-provenance.md"
METHODS = ("get", "post", "put", "patch", "delete", "head", "options")

# Which generated artifact comes from which source, keyed by a substring of
# the URL. Stated here so the table says what each document is FOR; a digest
# nobody can connect to an artifact is trivia.
DERIVES = {
    "console": ["`docs/API_COVERAGE.md`", "`internal/workflow/operations.json`"],
    "insights": ["`docs/API_COVERAGE.md`"],
}


def describe(path):
    """Return (sha256, operation count, title) for one spec document."""
    raw = open(path, "rb").read()
    spec = yaml.safe_load(raw.decode("utf-8"))
    ops = 0
    for _, item in (spec.get("paths") or {}).items():
        if not isinstance(item, dict):
            continue
        for m, op in item.items():
            if m.lower() in METHODS and isinstance(op, dict):
                ops += 1
    if not ops:
        sys.exit(f"no operations found in {path} — wrong file?")
    title = spec.get("info", {}).get("title") or "API"
    return hashlib.sha256(raw).hexdigest(), ops, title


def main():
    out = OUT
    pairs = []
    for arg in sys.argv[1:]:
        if arg.startswith("--out="):
            out = arg.split("=", 1)[1]
        elif "=" in arg:
            url, path = arg.split("=", 1)
            pairs.append((url, path))
        else:
            sys.exit(f"expected URL=path, got {arg!r}")
    if not pairs:
        sys.exit("usage: spec-provenance.py URL=path [URL=path ...] [--out=PATH]")

    lines = []
    lines.append("# Spec provenance\n")
    lines.append(
        "_Generated by `scripts/spec-provenance.py`. Do not edit by hand; run "
        "`make refresh-generated` to rebuild it._\n")
    lines.append(
        "The upstream documents the generated artifacts in this repo were built "
        "from. There is deliberately no date here — git holds that, and more "
        "reliably than a self-reported string:\n")
    lines.append("```\ngit log -1 --format=%ad -- docs/API_COVERAGE.md\n```\n")
    lines.append(
        "A date in the file would also defeat `make verify-generated`, which "
        "regenerates these artifacts and fails on any difference: every "
        "regeneration would differ and the check could no longer tell a moved "
        "spec from a rerun script.\n")

    # Parsed once per document: these specs are megabytes, and the earlier
    # version of this loop called describe() a second time to total the
    # counts, which doubled the work for a number it already had.
    described = [(url, describe(path)) for url, path in pairs]

    lines.append("| Source | Operations | SHA-256 | Derives |\n|---|---:|---|---|")
    for url, (digest, ops, _) in described:
        key = next((k for k in DERIVES if k in url), None)
        derives = ", ".join(DERIVES.get(key, ["—"]))
        lines.append(f"| <{url}> | {ops} | `{digest}` | {derives} |")

    lines.append(
        "\nThe digest covers the whole document, so upstream reformatting or an "
        "edited description moves it while nothing jc derives changes. That is "
        "the point of the split: this file answers *is it the same document?*, "
        "and the regenerated artifacts answer *did anything we depend on "
        "change?*. A drift PR whose only diff is a digest means upstream "
        "republished and jc is unaffected.\n")

    open(out, "w").write("\n".join(lines) + "\n")
    total = sum(ops for _, (_, ops, _) in described)
    print(f"wrote {out} — {len(pairs)} source document(s), {total} operations")


if __name__ == "__main__":
    main()
